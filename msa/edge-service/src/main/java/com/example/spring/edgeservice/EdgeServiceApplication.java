package com.example.spring.edgeservice;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;

// * MSA(Microservice Architecture)란?
// 하나의 애플리케이션을, 각자 독립적으로 배포/확장/실패 할 수 있는
// 작은 서비스들의 협력으로 바꾸는 아키텍처 스타일이다.

// 모놀리스 : 전 기능이 한 프로세스/한 배포 단위/한 DB. 메서드 호출로 협력한다.
// -> 단순하고 빠르다.(트랜잭션 하나로 정합성 해결). 문제는 "전부가 한 몸"이라는 것
// -> 한 기능의 배포가 전체 재배포이고, 한 기능의 부하가 전체를 느리게 하고,
// -> 한 기능의 장애가 프로세스 전체를 죽인다.
// MSA : 기능을 프로세스 경계로 가른다. 협력은 메서드 호출이 아니라 네트워크(HTTP/이벤트)로.

// MSA가 왜 필요한가?
// 1. 독립 배포 : 게시판 검색 로직을 고치는 데 인증 서버를 재배포할 이유가 없다.
// 배포 단위가 작아지면 배포 빈도는 오르고 실패 반경은 준다.
// 2. 독립 확장 : 조회 폭주는 board만 스케일 아웃하면 된다. 모놀리스는 전체를 복제해야 한다.
// 3. 장애 격리(전파 방지) : 한 서비스의 죽음이 "전체의 죽음"이 아니라 "부분 기능 저하"가 되게 한다.
// 단, 공짜가 아니다. - 프로세스를 갈랐다고 저절로 격리되지 않는다.
// 동기 호출은 장애를 그대로 전파하므로, 격리는 설계해야 한다..
// - 폴백 : auth가 죽어도 board 목록은 뜬다 - 작성자 이름만 비운 상태로
// - 보상 : board가 죽어도 탈퇴는 안전하게 실패한다. - 계정 상태 원복 후 503 (탈퇴 Saga)

// Database per Service - 데이터도 서비스 경계를 따른다.
// 원칙 : 각 서비스는 자기 데이터베이스를 소유하고, 다른 서비스의 DB에는 직접 접근하지 않는다.
// 다른 서비스의 데이터가 필요하면 그 서비스의 API(또는 이벤트)를 통해서만 얻는다.

// 왜 프로세스만이 아니라 DB까지 가르는가?
// DB를 공유하면 분리가 무효가 되기 때문
// - 결합이 스키마 밑으로 숨는다. : 두 서비스가 한테이블을 읽으면, 컬럼 하나 바꾸는 데
// 두 서비스를 동시에 고치고 동시에 배포해야 한다. - "독립 배포"가 그 순간 거짓이 된다.
// - 소유권이 사라진다. : 데이터를 누가 지키는가가 불분명해진다.
// DB가 곧 경계이면 "user의 진실은 auth만 쓴다"가 물리적으로 강제된다.

// 갈라서 잃는 것과 그 대응
// - 조인 상실 : board는 더 이상 member를 left join해서 작성자 이름을 얻을 수 없다.
// 1. API composition : 조회 시 소유자에게 묻기 - board -> auth 이름 벌크 조회
// 2. 복제/스냅샷(내 DB에 사본을 두고 이벤트로 동기화)
// 3. CQRS 읽기 모델(조회 전용 저장소를 따로 구축)
// - 트랜잭션 상실 : 두 DB의 커밋을 하나로 묶을 수 없다 -> Saga/보상
// - FK 상실 : board.user_id는 이제 user를 가리키는 외래키가 아니라 "느슨한 참조"다

// MSA는 정답이 아니라 트레이드오프다.
// 갈라진 경계마다 비용이 생긴다.
// - 지연 : 메서드 호출(ns)이 네트워크 호출(ms)이 된다.
// - 부분 실패 : 모놀리스에서 없던 실패 유형 - "절반만 성공"이 빈번해진다.
// - 정합성 : 트랜잭션 하나로 묶던 것을 못 묶는다.
// - 운영 복잡도 : 서비스 수 만큼 배포/설정/관측이 늘어난다.

// edge service
// 서비스가 갈라지면 클라이언트가 "여러 주소"를 알아야 하는 문제가 생긴다.
// API Gateway는 그 지형을 하나의 문 뒤로 숨긴다. - 브라우저의 API주소는 8000 하나로 고정된다.
// 뒤에서 서비스가 늘거나 포트가 바뀌어도 클라이언트는 불변이다.


@SpringBootApplication
public class EdgeServiceApplication {

    public static void main(String[] args) {
        SpringApplication.run(EdgeServiceApplication.class, args);
    }

}
